'use server';
/**
 * @fileOverview Suggests restaurants based on user preferences and ratings.
 *
 * - suggestRestaurantsBasedOnPreferences - A function that suggests restaurants based on user preferences.
 * - SuggestRestaurantsBasedOnPreferencesInput - The input type for the suggestRestaurantsBasedOnPreferences function.
 * - SuggestRestaurantsBasedOnPreferencesOutput - The return type for the suggestRestaurantsBasedOnPreferences function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const SuggestRestaurantsBasedOnPreferencesInputSchema = z.object({
  userPreferences: z
    .string()
    .describe('The user preferences for restaurants.'),
  userRatings: z.string().describe('The user ratings of other restaurants.'),
  location: z
    .string()
    .describe('The user location to find nearby restaurants.'),
});
export type SuggestRestaurantsBasedOnPreferencesInput = z.infer<
  typeof SuggestRestaurantsBasedOnPreferencesInputSchema
>;

const SuggestRestaurantsBasedOnPreferencesOutputSchema = z.object({
  suggestedRestaurants: z
    .string()
    .describe('A list of suggested restaurants based on user preferences.'),
});
export type SuggestRestaurantsBasedOnPreferencesOutput = z.infer<
  typeof SuggestRestaurantsBasedOnPreferencesOutputSchema
>;

export async function suggestRestaurantsBasedOnPreferences(
  input: SuggestRestaurantsBasedOnPreferencesInput
): Promise<SuggestRestaurantsBasedOnPreferencesOutput> {
  return suggestRestaurantsBasedOnPreferencesFlow(input);
}

const prompt = ai.definePrompt({
  name: 'suggestRestaurantsBasedOnPreferencesPrompt',
  input: {schema: SuggestRestaurantsBasedOnPreferencesInputSchema},
  output: {schema: SuggestRestaurantsBasedOnPreferencesOutputSchema},
  prompt: `You are a restaurant recommendation expert.

  Based on the user's preferences: {{{userPreferences}}},
  their ratings of other restaurants: {{{userRatings}}},
  and their current location: {{{location}}},

  suggest a list of restaurants that the user might enjoy.
  Make sure to only include restaurants that are near the specified location.
  Format your response as a list of restaurant names and descriptions.
`,
});

const suggestRestaurantsBasedOnPreferencesFlow = ai.defineFlow(
  {
    name: 'suggestRestaurantsBasedOnPreferencesFlow',
    inputSchema: SuggestRestaurantsBasedOnPreferencesInputSchema,
    outputSchema: SuggestRestaurantsBasedOnPreferencesOutputSchema,
  },
  async input => {
    const {output} = await prompt(input);
    return output!;
  }
);























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































